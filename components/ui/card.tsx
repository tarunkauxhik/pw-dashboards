import * as React from "react";
import { cn } from "@/lib/utils";

export const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-lg border border-border/60 bg-card text-card-foreground shadow-[0_1px_2px_rgba(0,0,0,0.04)]",
      className,
    )}
    {...props}
  />
));
Card.displayName = "Card";

export const CardHeader = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { action?: React.ReactNode }
>(({ className, action, children, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "flex gap-1.5 p-5 pb-3",
      action ? "flex-row items-start justify-between" : "flex-col",
      className,
    )}
    {...props}
  >
    <div className="flex flex-col gap-1.5">{children}</div>
    {action && <div className="shrink-0">{action}</div>}
  </div>
));
CardHeader.displayName = "CardTitle";

